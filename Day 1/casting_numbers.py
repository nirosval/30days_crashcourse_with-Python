# From int to float
num_int = 15
print('num_int:',num_int)
num_float = float(num_int)
print('num_float:', num_float)

# float to int
num_float = 20.04
int_num = int(num_float)
print("int_num:", int_num)

pace = 3.40
print(int(pace))

# int to string
num_int = 22
print('num_int:', num_int)
num_string = str(num_int)
print('num_string:', num_string)

# string to int or float
num_string = '2004'
num_int = int(num_string)
num_float = float(num_string)
print('num_int:', num_int)
print('num_float:', num_float)

# str to list
full_name = 'plongplong_coder'
name_list = list(full_name)
print('name_list:', name_list)

# string to boolean
num_string = 'plongplong_coder'
num_bool = bool(num_string)
print('num_bool:', num_bool)
